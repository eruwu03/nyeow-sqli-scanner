"""Writes scan results to the local output directory (JSON and/or HTML).

Data handling rules:
  * reports are written ONLY to the local run folder - nothing is uploaded,
  * no response bodies, cookies or extracted data are stored, only short
    evidence snippets that prove the finding,
  * every report is labelled CONFIDENTIAL with the authorized scope.
"""

import html
import json
from pathlib import Path

from . import TOOL_NAME, __version__
from .scanner import ScanResult

LABEL = "CONFIDENTIAL - security test results for the authorized scope only. Do not distribute."
REMEDIATION = (
    "Use parameterized queries / prepared statements for every database call, "
    "validate input against an allow-list, run the database account with least "
    "privilege, and disable detailed database error messages in production."
)


def build_report_data(result: ScanResult) -> dict:
    return {
        "label": LABEL,
        "tool": {"name": TOOL_NAME, "version": __version__},
        "scan": {
            "target": result.target,
            "authorized_scope": result.scope,
            "techniques": result.techniques,
            "status": result.status,
            "started": result.started.isoformat(timespec="seconds"),
            "finished": result.finished.isoformat(timespec="seconds") if result.finished else None,
            "duration_seconds": round(result.duration, 1),
            "requests_sent": result.requests_sent,
            "endpoints": len(result.points),
            "parameters_tested": result.params_tested,
        },
        "findings": [f.to_dict() | {"remediation": REMEDIATION} for f in result.findings],
        "endpoints": [{"method": p.method, "url": p.url, "parameters": p.testable_params,
                       "source": p.source} for p in result.points],
        "skipped_for_safety": result.skipped,
    }


def write_json(data: dict, run_dir: Path) -> Path:
    path = run_dir / "report.json"
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")
    return path


def write_html(data: dict, run_dir: Path) -> Path:
    e = lambda value: html.escape(str(value))  # every value is escaped: payloads contain quotes/tags
    scan = data["scan"]
    summary_rows = "".join(
        f"<tr><th>{e(k.replace('_', ' ').title())}</th><td>{e(v)}</td></tr>"
        for k, v in scan.items() if k != "techniques")
    if data["findings"]:
        finding_cards = "".join(f"""
<div class="finding">
  <h3><span class="sev">{e(f['severity'])}</span> {e(f['technique'])} SQL injection in
      <code>{e(f['parameter'])}</code></h3>
  <table>
    <tr><th>Request</th><td>{e(f['method'])} {e(f['url'])}</td></tr>
    <tr><th>Payload</th><td><code>{e(f['payload'])}</code></td></tr>
    <tr><th>DBMS</th><td>{e(f['dbms'])}</td></tr>
    <tr><th>Confidence</th><td>{e(f['confidence'])}</td></tr>
    <tr><th>Evidence</th><td>{e(f['evidence'])}</td></tr>
    <tr><th>Remediation</th><td>{e(f['remediation'])}</td></tr>
  </table>
</div>""" for f in data["findings"])
    else:
        finding_cards = "<p class='ok'>No SQL injection found in the tested parameters.</p>"
    endpoint_rows = "".join(
        f"<tr><td>{e(p['method'])}</td><td>{e(p['url'])}</td><td>{e(', '.join(p['parameters']))}</td></tr>"
        for p in data["endpoints"]) or "<tr><td colspan=3>none</td></tr>"
    skipped = "".join(f"<li>{e(s)}</li>" for s in data["skipped_for_safety"]) or "<li>none</li>"

    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(TOOL_NAME)} report - {e(scan['target'])}</title>
<style>
 body{{font-family:system-ui,sans-serif;max-width:960px;margin:2rem auto;padding:0 1rem;color:#1d2330;background:#fafbfc}}
 .label{{background:#b3261e;color:#fff;padding:.6rem 1rem;border-radius:6px;font-weight:600}}
 table{{border-collapse:collapse;width:100%;margin:.5rem 0 1rem}}
 th,td{{text-align:left;padding:.4rem .6rem;border-bottom:1px solid #dde1e7;vertical-align:top;word-break:break-word}}
 th{{width:22%;color:#4a5263}}
 code{{background:#eef0f4;padding:.1rem .3rem;border-radius:4px}}
 .finding{{border:1px solid #e3b5b2;border-left:6px solid #b3261e;background:#fff;border-radius:6px;padding:.5rem 1rem;margin:1rem 0}}
 .sev{{background:#b3261e;color:#fff;border-radius:4px;padding:.1rem .5rem;font-size:.8rem}}
 .ok{{color:#1e7a3c;font-weight:600}}
</style></head><body>
<p class="label">{e(LABEL)}</p>
<h1>{e(TOOL_NAME)} scan report</h1>
<p>Generated by {e(TOOL_NAME)} v{e(data['tool']['version'])}. Detection only: no data was extracted from the target.</p>
<h2>Summary</h2><table>{summary_rows}
<tr><th>Techniques</th><td>{e(', '.join(scan['techniques']))}</td></tr></table>
<h2>Findings ({len(data['findings'])})</h2>{finding_cards}
<h2>Endpoints tested</h2>
<table><tr><th>Method</th><th>URL</th><th>Parameters</th></tr>{endpoint_rows}</table>
<h2>Skipped for safety</h2><ul>{skipped}</ul>
</body></html>"""
    path = run_dir / "report.html"
    path.write_text(page, encoding="utf-8")
    return path


def write_reports(result: ScanResult, run_dir: Path, formats: list[str]) -> list[Path]:
    data = build_report_data(result)
    writers = {"json": write_json, "html": write_html}
    return [writers[fmt](data, run_dir) for fmt in formats if fmt in writers]
